const originalText = new WeakMap<Text, string>();
const originalAttributes = new WeakMap<Element, Map<string, string>>();

function normalized(value: string): string {
  return value.replace(/\s+/g, " ").trim();
}

export function localizePhrase(value: string, language: Language): string {
  const phrase = normalized(value);
  if (language === "fr") return translations[phrase] ?? value;
  const original = Object.entries(translations).find(([, translated]) => normalized(translated) === phrase)?.[0];
  return original ?? value;
}

function translatePage(language: Language): void {
  document.documentElement.lang = language;

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    const textNode = node as Text;
    if (!originalText.has(textNode)) originalText.set(textNode, textNode.nodeValue ?? "");
    const source = originalText.get(textNode) ?? "";
    const trimmed = source.trim();
    const translation = localizePhrase(trimmed, language);
    if (translation !== trimmed) {
      const leading = source.match(/^\s*/)?.[0] ?? "";
      const trailing = source.match(/\s*$/)?.[0] ?? "";
      textNode.nodeValue = `${leading}${translation}${trailing}`;
    } else if (language === "en") {
      textNode.nodeValue = source;
    }
    node = walker.nextNode();
  }

  const attributes = ["aria-label", "alt", "placeholder", "title"];
  document.querySelectorAll<Element>(attributes.map((name) => `[${name}]`).join(",")).forEach((element) => {
    let originals = originalAttributes.get(element);
    if (!originals) {
      originals = new Map();
      originalAttributes.set(element, originals);
    }

    attributes.forEach((attribute) => {
      const current = element.getAttribute(attribute);
      if (current === null) return;
      if (!originals.has(attribute)) originals.set(attribute, current);
      const source = originals.get(attribute) ?? current;
      element.setAttribute(attribute, localizePhrase(source, language));
    });
  });

  const title = document.querySelector("title");
  if (title) {
    if (!title.dataset.originalTitle) title.dataset.originalTitle = title.textContent ?? "";
    title.textContent = localizePhrase(title.dataset.originalTitle, language);
  }

  const languageButton = document.querySelector<HTMLButtonElement>("#language-toggle");
  if (languageButton) {
    languageButton.textContent = language === "en" ? "FR" : "EN";
    languageButton.setAttribute("aria-label", language === "en" ? "Switch to French" : "Passer en anglais");
    languageButton.setAttribute("aria-pressed", String(language === "fr"));
  }
}

function initAccessibility(): void {
  const language: Language = localStorage.getItem("portfolio-language") === "fr" ? "fr" : "en";
  const scale = localStorage.getItem("portfolio-text-scale");
  const dyslexia = localStorage.getItem("portfolio-dyslexia") === "true";
  const contrast = localStorage.getItem("portfolio-contrast") === "true";
  const reducedMotion = localStorage.getItem("portfolio-reduced-motion") === "true";

  document.documentElement.style.setProperty("--accessibility-font-size", scale === "large" ? "18px" : scale === "small" ? "15px" : "16px");
  document.body.classList.toggle("a11y-dyslexia", dyslexia);
  document.body.classList.toggle("a11y-high-contrast", contrast);
  document.body.classList.toggle("a11y-reduced-motion", reducedMotion);
  translatePage(language);

  const panel = document.querySelector<HTMLElement>(".accessibility-panel");
  if (!panel || panel.dataset.ready === "true") return;
  panel.dataset.ready = "true";

  document.querySelector<HTMLButtonElement>("#language-toggle")?.addEventListener("click", () => {
    const nextLanguage: Language = document.documentElement.lang === "fr" ? "en" : "fr";
    localStorage.setItem("portfolio-language", nextLanguage);
    translatePage(nextLanguage);
  });

  document.querySelector<HTMLButtonElement>("#text-smaller")?.addEventListener("click", () => {
    localStorage.setItem("portfolio-text-scale", "small");
    document.documentElement.style.setProperty("--accessibility-font-size", "15px");
  });

  document.querySelector<HTMLButtonElement>("#text-larger")?.addEventListener("click", () => {
    localStorage.setItem("portfolio-text-scale", "large");
    document.documentElement.style.setProperty("--accessibility-font-size", "18px");
  });

  document.querySelector<HTMLButtonElement>("#dyslexia-toggle")?.addEventListener("click", (event) => {
    const enabled = (event.currentTarget as HTMLButtonElement).getAttribute("aria-pressed") !== "true";
    localStorage.setItem("portfolio-dyslexia", String(enabled));
    document.body.classList.toggle("a11y-dyslexia", enabled);
    (event.currentTarget as HTMLButtonElement).setAttribute("aria-pressed", String(enabled));
  });

  document.querySelector<HTMLButtonElement>("#contrast-toggle")?.addEventListener("click", (event) => {
    const enabled = (event.currentTarget as HTMLButtonElement).getAttribute("aria-pressed") !== "true";
    localStorage.setItem("portfolio-contrast", String(enabled));
    document.body.classList.toggle("a11y-high-contrast", enabled);
    (event.currentTarget as HTMLButtonElement).setAttribute("aria-pressed", String(enabled));
  });

  document.querySelector<HTMLButtonElement>("#motion-toggle")?.addEventListener("click", (event) => {
    const enabled = (event.currentTarget as HTMLButtonElement).getAttribute("aria-pressed") !== "true";
    localStorage.setItem("portfolio-reduced-motion", String(enabled));
    document.body.classList.toggle("a11y-reduced-motion", enabled);
    (event.currentTarget as HTMLButtonElement).setAttribute("aria-pressed", String(enabled));
  });

  document.querySelector<HTMLButtonElement>("#accessibility-reset")?.addEventListener("click", () => {
    ["portfolio-text-scale", "portfolio-dyslexia", "portfolio-contrast", "portfolio-reduced-motion"].forEach((key) => localStorage.removeItem(key));
    document.documentElement.style.setProperty("--accessibility-font-size", "16px");
    document.body.classList.remove("a11y-dyslexia", "a11y-high-contrast", "a11y-reduced-motion");
    panel.querySelectorAll<HTMLButtonElement>("[aria-pressed]").forEach((button) => button.setAttribute("aria-pressed", "false"));
  });

  panel.querySelector<HTMLButtonElement>("#dyslexia-toggle")?.setAttribute("aria-pressed", String(dyslexia));
  panel.querySelector<HTMLButtonElement>("#contrast-toggle")?.setAttribute("aria-pressed", String(contrast));
  panel.querySelector<HTMLButtonElement>("#motion-toggle")?.setAttribute("aria-pressed", String(reducedMotion));
}

document.addEventListener("astro:page-load", initAccessibility);
document.addEventListener("DOMContentLoaded", initAccessibility);
